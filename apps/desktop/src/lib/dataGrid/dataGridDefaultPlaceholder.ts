import type { CellValue } from "@/lib/dataGrid/cellValue";
import type { ColumnInfo } from "@/types/database";

export interface DataGridNewRowPlaceholderRow {
  data: readonly CellValue[];
  isNew: boolean;
  isDraft?: boolean;
}

export function isColumnAutoGenerated(column: ColumnInfo | Pick<ColumnInfo, "column_default" | "extra"> | undefined, databaseType?: string): boolean {
  if (!column) return false;
  const extra = column.extra ?? "";
  const columnDefault = column.column_default ?? "";
  const dataType = "data_type" in column ? (column.data_type ?? "") : "";
  const normalizedDatabaseType = databaseType?.toLowerCase();
  const normalizedDataType = dataType.trim().replace(/^"|"$/g, "").toLowerCase();
  if (/\b(auto_increment|autoincrement|identity|smallserial|serial|bigserial)\b/i.test(extra)) return true;
  if (/\b(?:generated\s+(?:always|by\s+default)\s+as|(?:virtual|stored)\s+generated)\b/i.test(extra)) return true;
  if (/\b(smallserial|serial|bigserial)\b/i.test(dataType)) return true;
  if (/\bnextval\s*\(/i.test(columnDefault) || /\.nextval\b/i.test(columnDefault)) return true;
  if (normalizedDatabaseType === "sqlserver") {
    if (extra.trim().toLowerCase() === "computed") return true;
    if (["timestamp", "rowversion"].includes(normalizedDataType.split(/[ (\t\r\n]/, 1)[0] ?? "")) return true;
  }
  if ("is_identity" in column && Boolean((column as { is_identity?: boolean }).is_identity)) return true;
  if ("is_computed" in column && Boolean((column as { is_computed?: boolean }).is_computed)) return true;
  return false;
}

export function resolveDataGridNewRowCellPlaceholder(options: { row: DataGridNewRowPlaceholderRow | undefined; columnIndex: number; column: ColumnInfo | Pick<ColumnInfo, "column_default" | "extra"> | undefined; draftFallback: string; databaseType?: string }): string | null {
  const { row, columnIndex, column, draftFallback, databaseType } = options;
  if (!row || (!row.isNew && !row.isDraft) || row.data[columnIndex] !== null) return null;

  if (isColumnAutoGenerated(column, databaseType)) {
    return "<generated>";
  }

  const rawDefault = column?.column_default;
  if (rawDefault != null) {
    const normalizedDefault = rawDefault.trim();
    if (normalizedDefault && normalizedDefault.toUpperCase() !== "NULL") return rawDefault;
  }

  return row.isDraft ? draftFallback : null;
}
